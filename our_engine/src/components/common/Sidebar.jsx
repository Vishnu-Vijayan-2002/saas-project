export default function Sidebar({ isOpen, onClose }) {
  const { user, userProfile, logout } = useAuth();
  const { tenantName } = useTenant();

  if (!user) return null;

  const navItems = getNavigationForRole(user.role);
  const displayName = userProfile?.name || user.displayName || user.email?.split('@')[0] || 'User';
  const initials = displayName.slice(0, 2).toUpperCase();

  const brandName = user.role === 'SUPER_ADMIN' ? 'OurEngine' : tenantName;
  const roleLabelMap = {
    SUPER_ADMIN: 'Platform Admin',
    BUSINESS_ADMIN: 'Business Admin',
    SALESMAN: 'Delivery Agent',
    CUSTOMER: 'Customer',
  };

  const handleLogout = async () => {
    try {
      await logout();
    } catch (err) {
      console.error('Logout failed:', err);
    }
  };

  return (
    <>
      {/* Mobile overlay */}
      <div
        className={`sidebar-overlay ${isOpen ? 'visible' : ''}`}
        onClick={onClose}
      />

      <aside className={`sidebar ${isOpen ? 'open' : ''}`}>
        {/* Brand */}
        <div className="sidebar-brand">
          <div className="sidebar-brand__logo">O</div>
          <div className="sidebar-brand__text">
            <span className="sidebar-brand__name">{brandName}</span>
            <span className="sidebar-brand__role">{roleLabelMap[user.role] || user.role}</span>
          </div>
        </div>

        {/* Navigation */}
        <nav className="sidebar-nav">
          {navItems.map((item) => (
            <NavLink
              key={item.path}
              to={item.path}
              className={({ isActive }) => `sidebar-link ${isActive ? 'active' : ''}`}
              onClick={onClose}
            >
              <span className="sidebar-link__icon">
                {icons[item.icon] || icons.dashboard}
              </span>
              {item.label}
            </NavLink>
          ))}
        </nav>

        {/* Footer */}
        <div className="sidebar-footer">
          <div className="sidebar-user">
            <div className="sidebar-user__avatar">{initials}</div>
            <div className="sidebar-user__info">
              <div className="sidebar-user__name">{displayName}</div>
              <div className="sidebar-user__email">{user.email}</div>
            </div>
          </div>
          <button
            className="sidebar-link"
            onClick={handleLogout}
            style={{ marginTop: 'var(--space-2)', width: '100%' }}
          >
            <span className="sidebar-link__icon">{icons.logout}</span>
            Logout
          </button>
        </div>
      </aside>
    </>
  );
}
